def _json(raw):
    value = json.loads(raw.decode('utf-8'), object_pairs_hook=_unique_object,
                       parse_constant=_invalid_constant)
    if type(value) is not dict:
        raise JobError('l2-json-object-required')
    return value


def _hash(path, limit):
    _regular_file(path)
    before = path.stat()
    if not 0 < before.st_size <= limit:
        raise JobError('l2-package-file-size')
    result = hashlib.sha256()
    count = 0
    header = b''
    with path.open('rb') as stream:
        opened = os.fstat(stream.fileno())
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            if not header:
                header = block[:20]
            count += len(block)
            if count > limit:
                raise JobError('l2-package-file-size')
            result.update(block)
        after = os.fstat(stream.fileno())
    _regular_file(path)
    def key(s):
        return s.st_dev, s.st_ino, s.st_size, s.st_mtime_ns, s.st_ctime_ns
    if not key(before) == key(opened) == key(after) == key(path.stat()):
        raise JobError('l2-package-file-changed')
    return result.hexdigest(), before.st_size, header


def source_identity(checkout):
    """Match the legacy build's recorded status/diff digest, not an attestation."""
    checkout = Path(checkout)
    def git(*args):
        value = subprocess.run(['git', '-c', 'safe.directory=' + checkout.as_posix(), '-C',
                                str(checkout), *args], capture_output=True, timeout=60,
                               check=True).stdout
        return value.replace(b'\r\n', b'\n')
    sha = git('rev-parse', 'HEAD').decode('ascii').strip()
    status = git('status', '--porcelain=v1', '-uall', '--no-renames')
    diff = git('diff', 'HEAD', '--binary', '--no-ext-diff')
    return dict(source_sha=sha, source_dirty=bool(status.strip()),
                source_dirty_digest=hashlib.sha256(status + b'\n--\n' + diff).hexdigest())


def _checkout_text(path, *, strip):
    _regular_file(path)
    with path.open('rb') as stream:
        raw = stream.read(256 * 1024 + 1)
    if len(raw) > 256 * 1024:
        raise JobError('l2-checkout-file-size')
    raw = raw.replace(b'\r\n', b'\n')
    return raw.rstrip(b'\n') + b'\n' if strip else raw


def validate_package(directory, *, checkout, immutable=False, check_source=True,
                     profile='l2', sing_box_sha256=None, requests_directory=None,
                     without_requests=False):
    """Stream hash existing binaries; reject any extra file, directory or link.

    The generated L3 requests never belong to the owner's content. With
    requests_directory they are read from the run's own directory; with
    without_requests they are left out (the controller renders them in memory).
    Either way a request file inside `directory` is an error.
    """
    profile = profile_of(profile)
    root, checkout = Path(directory), Path(checkout)
    for path in (root, checkout):
        if not path.is_absolute() or '..' in path.parts:
            raise JobError('l2-absolute-path-required')
        _no_links(path)
    payload = profile.payload
    requests = tuple('artifacts/' + n for n in profile.requests)
    files = tuple(n for n in payload if n != "job.env") if immutable else profile.files
    external = requests_directory is not None or without_requests
    if external:
        if any(os.path.lexists(root / n) for n in requests):
            raise JobError('l3-requests-in-content')
        in_root = tuple(n for n in files if n not in requests)
    else:
        in_root = files
    if requests_directory is not None:
        requests_directory = Path(requests_directory)
        if not requests_directory.is_absolute() or '..' in requests_directory.parts:
            raise JobError('l2-absolute-path-required')
        _no_links(requests_directory)
        if sorted(os.listdir(requests_directory)) != sorted(profile.requests):
            raise JobError('l3-request-composition')
    else:
        files = in_root

    def locate(name):
        if requests_directory is not None and name in requests:
            return requests_directory / name.rpartition('/')[2]
        return root / name

    found = set()
    for parent, dirs, names in os.walk(root, followlinks=False):
        for name in dirs + names:
            path = Path(parent) / name
            _no_links(path)
            found.add(path.relative_to(root).as_posix())
    if found != set(in_root) | {'guest', 'artifacts'}:
        raise JobError('l2-package-composition')
    hashes, sizes, headers = {}, {}, {}
    for name in files:
        hashes[name], sizes[name], headers[name] = _hash(locate(name), profile.limit(name))
    small = {}
    for name in files:
        if name in profile.elf or name in profile.debs:
            continue
        _regular_file(locate(name))
        with locate(name).open('rb') as stream:
            raw = stream.read(256 * 1024 + 1)
        if len(raw) != sizes[name] or hashlib.sha256(raw).hexdigest() != hashes[name]:
            raise JobError('l2-package-file-changed')
        small[name] = raw
    for name in (() if immutable else ('manifest.sha256', 'job.env')):
        if b'\r' in small[name] or not small[name].endswith(b'\n'):
            raise JobError('l2-package-requires-lf')
    for name in profile.sources:
        raw = _checkout_text(checkout / 'tools/vm/linux' / name, strip=True)
        if hashlib.sha256(raw).hexdigest() != hashes[name]:
            raise JobError('l2-checkout-script-or-catalog-mismatch')
    for name, source in profile.packaged:
        raw = _checkout_text(checkout / source, strip=False)
        if hashlib.sha256(raw).hexdigest() != hashes['artifacts/' + name]:
            raise JobError('l2-checkout-packaging-mismatch')
    if not immutable:
        manifest = {}
        for line in small['manifest.sha256'].decode('ascii').splitlines():
            match = re.fullmatch(r'([0-9a-f]{64})  (.+)', line)
            if not match or match[2] not in payload or match[2] in manifest:
                raise JobError('l2-invalid-manifest')
            manifest[match[2]] = match[1]
        if manifest != {name: hashes[name] for name in payload}:
            raise JobError('l2-manifest-mismatch')
    provenance = _json(small['artifacts/provenance.json'])
    if (type(provenance.get('schema')) is not int or provenance['schema'] != 1 or
            provenance.get('target') != 'x86_64-unknown-linux-gnu' or
            provenance.get('stage', 'l2') != profile.stage):
        raise JobError('l2-provenance-target')
    source = source_identity(checkout) if check_source else {
        k: provenance.get(k) for k in ('source_sha', 'source_dirty', 'source_dirty_digest')}
    if (not re.fullmatch('[0-9a-f]{40}', source['source_sha']) or
            type(provenance.get('source_dirty')) is not bool or
            any(provenance.get(k) != v for k, v in source.items())):
        raise JobError('l2-provenance-checkout-mismatch')
    for name in profile.binaries:
        head = headers['artifacts/' + name]
        if (len(head) != 20 or head[:6] != b'\x7fELF\x02\x01' or
                head[16:18] not in (b'\x02\x00', b'\x03\x00') or head[18:20] != b'\x3e\x00'):
            raise JobError('l2-artifact-not-x86-64-elf')
    for name in profile.debs:
        if headers[name][:len(DEB_MAGIC)] != DEB_MAGIC:
            raise JobError('l2-artifact-not-a-debian-package')
    for name in profile.attested:
        artifacts = provenance.get('artifacts')
        entry = artifacts.get(name) if type(artifacts) is dict else None
        if type(entry) is not dict or entry.get('sha256') != hashes['artifacts/' + name]:
            raise JobError('l2-provenance-artifact-hash')
    if 'sing-box' in profile.binaries:
        # The engine is delivered by the owner, so only the configuration can vouch for it.
        if (type(sing_box_sha256) is not str or not re.fullmatch('[0-9a-f]{64}', sing_box_sha256) or
                hashes['artifacts/sing-box'] != sing_box_sha256):
            raise JobError('l3-sing-box-sha256-mismatch')
    elif profile.packages and sing_box_sha256 is not None:
        # The packages bring their own engines, which provenance.json vouches for with the packages.
        raise JobError('l3-sing-box-sha256-unused')
    env = {} if immutable else validate_env(small["job.env"], profile.name)
    addresses, kinds_left = set(), {False, True}
    for name in requests:
        if name not in small:
            continue
        # Each file must be what the generator makes for its own node, all for one node and all of one
        # kind: the ordinary requests or the diagnostic ones of a lab run.
        try:
            node = _json(small[name])['node']
            server, port = node['server'], node['port']
            kinds = {diagnostic for diagnostic in (False, True)
                     if small[name] == l3_requests.render_for(profile.name, server, port, diagnostic=diagnostic)[
                         name.rpartition('/')[2]]}
        except (KeyError, TypeError, ValueError):
            raise JobError('l3-request-invalid') from None
        # The two program requests are the same in both kinds, so a file narrows the choice, not names it.
        kinds_left &= kinds
        if not kinds_left:
            raise JobError('l3-request-not-generated')
        addresses.add((server, port))
    if len(addresses) > 1 or (addresses and env and
                              addresses != {(env['HOST_ADDRESS'], int(env['NODE_PORT']))}):
        raise JobError('l3-request-node-mismatch')
    rows = parse_catalog(small[profile.sources[-1]].decode('utf-8-sig'))
    result = dict(env=env, hashes=hashes, sizes=sizes, source=source, catalog=rows,
                  catalog_digest=digest(rows), provenance=provenance,
                  origin='recorded-checkout-match; not cryptographic proof of build origin')
    if profile.name != 'l2':
        result['profile'] = profile.name  # absent for L2, so its evidence keeps the old bytes
    return result


def poller_key_shape(value):
    """Whether a value is the blob of an ssh-ed25519 public key: its type, then 32 bytes, and nothing else."""
    if not re.fullmatch('[A-Za-z0-9+/]{68}', value):
        return False
    blob = base64.b64decode(value, validate=True)
    return len(blob) == 51 and blob.startswith(POLLER_KEY_HEAD)


def validate_env(raw, profile='l2'):
    profile = profile_of(profile)
    env = {}
    for line in raw.decode('ascii').splitlines():
        match = re.fullmatch(r'([A-Z_]+)=([A-Za-z0-9._:@/+=-]+)', line)
        if not match or match[1] in env:
            raise JobError('l2-invalid-job-env')
        env[match[1]] = match[2]
    optional = {LAB_MARKER_KEY, LAB_CONTROL_KEY} if profile.name in SERVICE_PROFILES else set()
    if profile.name == 'l4':
        optional.add(LAB_POLLER_KEY)
    if not set(profile.env) <= set(env) <= set(profile.env) | optional:
        raise JobError('l2-job-env-fields')
    if not re.fullmatch(r'[0-9]{8}T[0-9]{6}Z-[0-9a-f]{8}', env['RUN_ID']):
        raise JobError('l2-guest-run-id')
    _uuid(env['EXPECTED_BOOT_ID'])
    _uuid(env['BIOS_GUID'])
    _identifier(env['STAND_ID'])
    if (any(not re.fullmatch('[a-z_][a-z0-9_-]{0,31}', env[k]) for k in ('USER_A', 'USER_B'))
            or env['USER_A'] == env['USER_B']):
        raise JobError('l2-accounts')
    for key in ('SCENARIO_TIMEOUT_SECONDS', 'UNIT_TIMEOUT_SECONDS', 'JOB_TIMEOUT_SECONDS'):
        if not env[key].isdigit() or not 10 <= int(env[key]) <= 86400:
            raise JobError('l2-timeout-range')
    # Limit this first execution API to the legacy CLI's maximum job duration.
    if not 60 <= int(env['JOB_TIMEOUT_SECONDS']) <= 7200:
        raise JobError('l2-job-timeout-range')
    if profile.name in SERVICE_PROFILES:
        # The shapes run-l3.sh, run-proxy.sh and run-l5.sh accept, narrowed to documentation addresses and a real port.
        for key in ('HOST_ADDRESS', 'PROBE_ADDRESS', 'DNS_PROBE_ADDRESS'):
            if not re.fullmatch(r'[0-9]{1,3}(\.[0-9]{1,3}){3}', env[key]):
                raise JobError('l3-job-env-address')
            try:
                address = ipaddress.IPv4Address(env[key])
            except ValueError:
                raise JobError('l3-job-env-address') from None
            if not any(address in net for net in DOCUMENTATION_V4):
                raise JobError('l3-job-env-address-not-documentation')
        if not re.fullmatch(r'[0-9]{1,5}', env['NODE_PORT']) or not 1 <= int(env['NODE_PORT']) <= 65535:
            raise JobError('l3-job-env-port')
        if LAB_MARKER_KEY in env:
            # A documentation address and the port of the lab's marker service, nothing else.
            from .lab_protocol import PORTS
            host, _, port = env[LAB_MARKER_KEY].partition(':')
            try:
                address = ipaddress.IPv4Address(host) if re.fullmatch(r'[0-9]{1,3}(\.[0-9]{1,3}){3}', host) else None
            except ValueError:
                address = None
            if (address is None or not any(address in net for net in DOCUMENTATION_V4)
                    or port != str(PORTS['marker'])):
                raise JobError('l3-job-env-lab-marker')
        if LAB_CONTROL_KEY in env and (LAB_MARKER_KEY not in env or env[LAB_CONTROL_KEY] != 'stop-helper'):
            raise JobError('l3-job-env-lab-control')
    if LAB_POLLER_KEY in env and (LAB_MARKER_KEY not in env or not poller_key_shape(env[LAB_POLLER_KEY])):
        raise JobError('l4-job-env-poller-key')
    return env


class LinuxL2Job:
    """One installed launcher attempt; explicit channel recovery permits collection only."""

    _evidence = SmokeJob._evidence

    def __init__(self, vm, *, package_directory, checkout, enabled=False,
                 profile='l2', sing_box_sha256=None):
        self.vm = vm
        self.profile = profile_of(profile)
        self.sing_box_sha256 = sing_box_sha256
        self._create(package_directory, checkout, enabled)

    @classmethod
    def restore(cls, vm):
        """The job of an attached run, rebuilt from its saved plan, package record and run state.

        Only collection follows: the job is never submitted again. The identity
        saved at creation must name this run, VM, guest run and boot.
        """
        state = run_state.of(vm.run)
        record = state.document['job'] if state is not None else None
        if record is None:
            raise JobError('l2-job-state-missing')
        job = cls.__new__(cls)
        job.vm = vm
        try:
            package = None
            for name in PROFILES:
                path = resource_path(vm.run.directory, 'linux-' + name + '/package.json')
                if path.is_file() and path.stat().st_size:
                    package = _json(path.read_bytes())
                    break
            if package is None:
                raise JobError('l2-job-record-missing')
            job.profile = profile_of(package.get('profile', 'l2'))
            job._plan = resource_path(vm.run.directory, 'linux-' + job.profile.name + '/plan.json').read_bytes()
            _json(job._plan)
            identity = package['identity']
            ids = state.document['identities']
            # The job names the boot it started on, the first of the chain; the state's own boot is the last.
            first = state.document['boot_chain'][0] if state.document['boot_chain'] else ids['boot_id']
            if (type(identity) is not dict or identity.get('host_run_id') != vm.run._identity[0]
                    or identity.get('vm_uuid') != vm.vm_uuid or identity.get('guest_run_id') != ids['guest_run_id']
                    or identity.get('boot_id') != first or identity.get('stand_id') != vm.run._identity[1]):
                raise JobError('l2-job-identity-mismatch')
            deadline = state.document['deadlines']['job_deadline']
        except (KeyError, TypeError, OSError, ValueError):
            raise JobError('l2-job-record-unusable') from None
        job.sing_box_sha256 = None
        job._identity = tuple((k, identity[k]) for k in ('host_run_id', 'guest_run_id', 'stand_id', 'vm_uuid',
                                                         'boot_id', 'job_id', 'manifest_sha256'))
        job.submission, job.launcher, job.job = record['submission'], record['launcher'], record['job']
        job.pid, job.session = record['pid'], record['session']
        job.verification = 'UNVERIFIED'
        job.calls, job.polls = state.budget('job_calls'), state.budget('job_polls')
        job._looked = None
        job.grace = 0
        job.handles = {}
        job.assessment = None
        # The deadline was recorded on the real-time clock; carry it over to this process's monotonic one.
        job.deadline = time.monotonic() + (deadline - time.time())
        vm._linux_l2_job = job
        job._evidence('l2-restored')
        return job

    def load_assessment(self):
        """The assessment a dead controller already saved; nothing is asked of the guest."""
        raw = resource_path(self.vm.run.directory, 'linux-' + self.profile.name + '/assessment.json').read_bytes()
        self.assessment = _json(raw)
        self.verification = self.assessment['validation']['status']

    @property
    def _guest_lock(self):
        return self.vm._guest_lock

    @property
    def identity(self):
        return dict(self._identity)

    @property
    def plan(self):
        return _json(self._plan)

    @_guest_serialized
    def _create(self, directory, checkout, enabled):
        vm = self.vm
        vm._check()
        if (enabled is not True or vm.qga is None or
                any(getattr(vm, k, None) is not None for k in ('_linux_l2_job', '_smoke_job', '_smoke_package'))):
            raise JobError('l2-opt-in-and-unused-vm-required')
        delivery = getattr(vm, '_l2_import', None)
        if delivery is not None:
            delivery.require_ready()
        elif getattr(vm, '_l2_media', None) is not None:
            raise JobError('l2-media-requires-import-receipt')
        package = validate_package(directory, checkout=checkout, profile=self.profile.name,
                                   sing_box_sha256=self.sing_box_sha256)
        if delivery is not None and package['hashes']['manifest.sha256'] != delivery.identity['manifest_sha256']:
            raise JobError('l2-import-package-mismatch')
        env = package['env']
        observation = vm.guest_observation
        if (not observation or observation['result'] != 'observed' or vm.reset_pending or
                observation['qga_session_id'] != vm.qga.session_id or not vm.qga.valid or
                observation['boot_id'] != env['EXPECTED_BOOT_ID'] or vm.vm_uuid != env['BIOS_GUID'] or
                vm.run._identity[1] != env['STAND_ID']):
            raise JobError('l2-package-vm-or-boot-mismatch')
        identity = dict(host_run_id=_identifier(vm.run._identity[0]), guest_run_id=env['RUN_ID'],
                        stand_id=env['STAND_ID'], vm_uuid=_uuid(vm.vm_uuid),
                        boot_id=_uuid(observation['boot_id']), job_id='linux-' + self.profile.name,
                        manifest_sha256=package['hashes']['manifest.sha256'])
        self._identity = tuple(identity.items())
        plan = make_plan(identity['job_id'], 'prepared-' + self.profile.name, dict(mode='exploratory',
                         run_id=env['RUN_ID'], boot_id=identity['boot_id']))
        plan.update(catalog=package['catalog'], catalog_digest=package['catalog_digest'])
        validate_plan(plan)
        self._plan = json.dumps(plan, sort_keys=True).encode()
        self.submission = 'not-submitted'
        self.launcher = self.job = 'unknown'
        self.verification = 'UNVERIFIED'
        self.pid = self.session = None
        self.calls = self.polls = 0
        self._looked = None
        self.grace = 0
        self.handles = {}
        self.assessment = None
        # Each phase of a job with planned reboots has the job timeout, and each reboot its room.
        span = job_span(identity['job_id'], int(env['JOB_TIMEOUT_SECONDS']))
        self.deadline = time.monotonic() + span + 180
        state = run_state.of(vm.run)
        if state is not None:
            self._record(lambda: state.deadline('job_deadline', span + 180))
        vm._linux_l2_job = self
        self._save('plan.json', self._plan)
        self._save('package.json', json.dumps(dict(package, identity=identity), sort_keys=True).encode())
        self._evidence('l2-created')

    def _record(self, write):
        """Write one change of the run state; a write that fails stops the operation before the guest sees it."""
        try:
            write()
        except (OSError, ValueError):
            self.vm.evidence_failed = True
            raise JobError('l2-run-state-write-failed') from None

    def _remember(self):
        state = run_state.of(self.vm.run)
        if state is not None:
            # The job state is the guest's word: anything outside the plain alphabet is kept as such.
            job = self.job if type(self.job) is str and re.fullmatch(r'[A-Za-z0-9_-]{1,64}', self.job) else 'unrecognized'
            self._record(lambda: state.update('job', submission=self.submission, launcher=self.launcher, job=job,
                                              pid=self.pid, session=self.session))

    def _spent(self, value):
        """Record `value` job calls as spent before the call that makes it so."""
        state = run_state.of(self.vm.run)
        if state is not None:
            self._record(lambda: state.record('job_calls', value))

    def _save(self, name, data):
        relative = 'linux-' + self.profile.name + '/' + name
        try:
            write_file(self.vm.run, relative, data, mode='overwrite', require_registered=True,
                       forbid=self.vm.run._identity[2])
        except (OSError, ValueError):
            self.vm.evidence_failed = True
            raise JobError('l2-evidence-write-failed') from None

    def _begin(self):
        vm = self.vm
        vm._check()
        if (vm.process.poll() is not None or not vm.qga.valid or vm.qga.closed or
                vm.reset_pending or vm.last_boot_id != self._boot):
            raise JobError('l2-channel-or-boot-unverified')
        if time.monotonic() >= self.deadline + self.grace:
            raise JobError('l2-job-deadline')
        vm.qga.deadline = min(self.deadline + self.grace, time.monotonic() + 60)

    @property
    def _boot(self):
        """The boot the controller confirmed last: the end of its chain, not what the guest reports."""
        chain = self.vm.boot_chain
        return chain[-1] if chain else self.identity['boot_id']

    def _rpc(self, name, args, timeout=5):
        self._begin()
        if self.calls >= 112 or (self.calls >= 111 and name != 'guest-file-close'):
            raise JobError('l2-rpc-budget')
        self._spent(self.calls + 1)
        self.calls += 1
        return self.vm.qga._rpc(name, timeout, args)

    def _fresh_boot(self):
        self._begin()
        qga = self.vm.qga
        before = qga.calls
        if self.calls >= 111:
            raise JobError('l2-rpc-budget')
        previous_limit = qga._operation_limit
        qga._operation_limit = min(previous_limit, before + 112 - self.calls)
        previous_hook = qga.on_call
        if run_state.of(self.vm.run) is not None:
            # The probe's calls go to the session directly; each is recorded as a job call before it is sent.
            qga.on_call = lambda: self._spent(self.calls + qga.calls - before + 1)
        try:
            qga.jobs_enabled = True
            qga.probe(5)
            if qga.read_boot_id(5) != self._boot:
                raise JobError('l2-boot-changed')
        finally:
            self.calls += qga.calls - before
            qga._operation_limit = previous_limit
            qga.on_call = previous_hook

    @_guest_serialized
    def submit(self):
        if self.submission != 'not-submitted':
            raise JobError('l2-already-attempted-inspect-only')
        delivery = getattr(self.vm, '_l2_import', None)
        if delivery is not None:
            delivery.require_ready()
        if list(self.vm.boot_chain) != [self.identity['boot_id']]:
            # A guest that has been reset before its job exists is not the guest the package was made for.
            raise JobError('l2-boot-chain-before-submit')
        self._fresh_boot()
        self.submission = 'unknown'
        self.session = self.vm.qga.session_id
        self._remember()
        self._evidence('l2-submit-intent')
        try:
            guest = self.identity['guest_run_id']
            value = self._rpc('guest-exec', dict(path=LAUNCHER,
                arg=[guest, '/root/rosetun-l2-stage/' + guest, self.identity['manifest_sha256']],
                **{'capture-output': False}))
            if type(value) is not dict or set(value) != {'pid'} or type(value['pid']) is not int or not 0 < value['pid'] < 2**31:
                self.vm.qga.invalidate()
                raise JobError('l2-invalid-launcher-pid')
            self.pid = value['pid']
            self.submission, self.launcher = 'launcher-spawned', 'running'
        finally:
            self._remember()
            self._evidence('l2-submit-return', pid=self.pid, session_id=self.session)
        return self.snapshot()

    def wait(self, seconds, *, sleep=time.sleep, clock=time.monotonic):
        """Wait for the job to finish, at most `seconds`, by reading its status file; True once it has.

        A final status ends the wait early. A planned guest reset ends the agent's session: the controller sees
        the RESET itself and recovers the session here, and none of it spends a collection attempt. A look that
        fails for any other reason ends the looking, and the rest is waited out as a fixed wait always was; the
        collection then goes the way it always went. An unplanned reset is an error and is not caught.
        """
        vm, end = self.vm, clock() + seconds
        interval = max(POLL_SECONDS, -(-seconds // POLL_SPLIT))
        looking = self.submission != 'not-submitted' and vm.qga is not None and vm.qga.valid
        while True:
            remaining = end - clock()
            if remaining <= 0:
                return False
            sleep(min(interval, remaining))
            vm.watch_resets()
            if self._reset_pending():
                self._recover(end - clock(), sleep, clock)
                looking = True
                continue
            if not looking:
                continue
            if self.calls >= POLL_CALLS_LIMIT:
                self._evidence('l2-poll-stopped', reason='job-call-budget')
                looking = False
                continue
            try:
                if self._peek():
                    return True
            except (QgaError, OSError, ValueError, UnicodeError, RecursionError) as error:
                named = isinstance(error, (QgaError, JobError, LifecycleError))
                self._evidence('l2-poll-stopped', reason=str(error) if named else type(error).__name__)
                looking = False
                # The agent stops a few seconds before the machine resets, so a reset may be about to be told.
                for _ in range(RESET_GRACE_SECONDS // RESET_GRACE_STEP):
                    if self._reset_pending():
                        break
                    sleep(RESET_GRACE_STEP)
                    vm.watch_resets()
                if self._reset_pending():
                    self._recover(end - clock(), sleep, clock)
                    looking = True

    def _reset_pending(self):
        return self.vm.reset_pending and self.vm.reset_kind == 'guest'

    def _recover(self, remaining, sleep, clock):
        self._evidence('l2-guest-reset', boot_chain=len(self.vm.boot_chain), resets=self.vm.guest_resets)
        self.vm.await_rebooted_guest(timeout=min(REBOOT_SECONDS, max(60, remaining)), clock=clock, sleep=sleep)
        self._evidence('l2-guest-rebooted', boot_chain=len(self.vm.boot_chain))

    @_guest_serialized
    def _peek(self):
        """One look at the status file: has the job finished, on the boot the controller confirmed last?"""
        self._begin()
        path = '/var/lib/rosetun-l2/' + self.identity['guest_run_id'] + '/report/status.json'
        try:
            handle = self._rpc('guest-file-open', dict(path=path, mode='r'))
        except QgaError as error:
            # Refused means answered: the file is not there yet, which is no failure of the channel.
            if str(error) != 'qga-rpc-rejected':
                raise
            return False
        if type(handle) is not int or not 0 <= handle < 2**63:
            self.vm.qga.invalidate()
            raise JobError('l2-invalid-handle')
        data = bytearray()
        try:
            for _ in range(3):
                requested = STATUS_LIMIT + 1 - len(data)
                value = self._rpc('guest-file-read', dict(handle=handle, count=requested))
                if (type(value) is not dict or set(value) != {'count', 'eof', 'buf-b64'} or
                        type(value['count']) is not int or not 0 <= value['count'] <= requested or
                        type(value['eof']) is not bool or type(value['buf-b64']) is not str or
                        len(value['buf-b64']) > 4 * ((STATUS_LIMIT + 3) // 3) + 4):
                    raise JobError('l2-invalid-read')
                block = base64.b64decode(value['buf-b64'], validate=True)
                if base64.b64encode(block).decode() != value['buf-b64'] or len(block) != value['count']:
                    raise JobError('l2-invalid-read-count')
                data.extend(block)
                if len(data) > STATUS_LIMIT:
                    raise JobError('l2-result-size-limit')
                if value['eof']:
                    break
                if not block:
                    raise JobError('l2-read-no-progress')
            else:
                raise JobError('l2-read-block-limit')
        finally:
            if self.vm.qga.valid:
                if self._rpc('guest-file-close', dict(handle=handle)) != {}:
                    self.vm.qga.invalidate()
                    raise JobError('l2-invalid-close')
        status = _json(bytes(data))
        look = (status.get('state'), status.get('boot_id'))
        if look != self._looked:
            # Only a change of state or of boot is kept: a look at every scenario would fill the evidence file.
            self._looked = look
            self._evidence('l2-poll', state=str(look[0])[:32], boot_id=str(look[1])[:64])
        return (status.get('state') == 'finished' and status.get('run_id') == self.identity['guest_run_id']
                and status.get('boot_id') == self._boot)

    def _read(self, name):
        """The bytes of one result file; the journal is optional and gives None when the guest has none."""
        if name not in ('status', 'report', 'status-after', 'journal'):
            raise JobError('l2-unknown-result-file')
        suffix = {'report': 'report.json', 'journal': JOURNAL}.get(name, 'status.json')
        saved = f'{self.polls}/' + (JOURNAL if name == 'journal' else name + '.json')
        path = '/var/lib/rosetun-l2/' + self.identity['guest_run_id'] + '/report/' + suffix
        pending = self.vm.qga.session_id + ':open:' + str(self.calls)
        self.handles[pending] = 'unconfirmed'
        self._evidence('l2-open-intent', file=name)
        try:
            handle = self._rpc('guest-file-open', dict(path=path, mode='r'))
        except QgaError as error:
            # The guest answered and refused: no file, so no handle. Any other failure leaves it unconfirmed.
            if name != 'journal' or str(error) != 'qga-rpc-rejected':
                raise
            self.handles[pending] = 'rejected'
            self._evidence('l2-file', file=name, complete=False, size=0, absent=True)
            return None
        if type(handle) is not int or not 0 <= handle < 2**63:
            self.vm.qga.invalidate()
            raise JobError('l2-invalid-handle')
        self.handles[pending] = 'answered'
        key = self.vm.qga.session_id + ':' + str(handle)
        self.handles[key] = 'open'
        data, complete = bytearray(), False
        limit = {'report': REPORT_LIMIT, 'journal': JOURNAL_LIMIT}.get(name, 8192)
        try:
            for _ in range(limit // BLOCK + 2):
                requested = min(BLOCK, limit - len(data) + 1)
                value = self._rpc('guest-file-read', dict(handle=handle, count=requested))
                if (type(value) is not dict or set(value) != {'count', 'eof', 'buf-b64'} or
                        type(value['count']) is not int or not 0 <= value['count'] <= requested or
                        type(value['eof']) is not bool or type(value['buf-b64']) is not str or
                        len(value['buf-b64']) > 4 * ((BLOCK + 2) // 3)):
                    raise JobError('l2-invalid-read')
                block = base64.b64decode(value['buf-b64'], validate=True)
                if base64.b64encode(block).decode() != value['buf-b64'] or len(block) != value['count']:
                    raise JobError('l2-invalid-read-count')
                # One extra byte distinguishes an exact-size file from overflow.
                data.extend(block)
                if len(data) > limit:
                    raise JobError('l2-result-size-limit')
                if value['eof']:
                    complete = True
                    return bytes(data)
                if not block:
                    raise JobError('l2-read-no-progress')
            raise JobError('l2-read-block-limit')
        finally:
            try:
                self._save(saved, data)
                self._evidence('l2-file', file=name, complete=complete, size=len(data),
                               sha256=hashlib.sha256(data).hexdigest())
            finally:
                self.handles[key] = 'close-unconfirmed'
                if self.vm.qga.valid:
                    if self._rpc('guest-file-close', dict(handle=handle)) != {}:
                        self.vm.qga.invalidate()
                        raise JobError('l2-invalid-close')
                    self.handles[key] = 'closed'

    def _journal(self):
        """Keep the service's journal when the guest has one; a missing or oversized file changes nothing."""
        try:
            self._read('journal')
        except JobError as error:
            if str(error) != 'l2-result-size-limit':
                raise
            # The first bytes are retained, the limit and one more; the assessment does not depend on them.
            self._evidence('l2-file', file='journal', complete=False, over_limit=True)

    @_guest_serialized
    def collect(self):
        self.verification = 'UNVERIFIED'
        self.assessment = None
        try:
            if self.submission == 'not-submitted' or self.polls >= POLLS:
                raise JobError('l2-not-submitted-or-poll-limit')
            state = run_state.of(self.vm.run)
            if state is not None:
                self._record(lambda: state.record('job_polls', self.polls + 1))
            self.polls += 1
            self._fresh_boot()
            if self.session != self.vm.qga.session_id:
                if self.launcher in ('running', 'unknown'):
                    self.launcher = 'unknown-after-recovery'
            elif self.pid is not None and self.launcher == 'running':
                value = self._rpc('guest-exec-status', dict(pid=self.pid))
                if type(value) is not dict or type(value.get('exited')) is not bool:
                    raise JobError('l2-invalid-exec-status')
                if value['exited']:
                    if set(value) != {'exited', 'exitcode'} or type(value['exitcode']) is not int:
                        raise JobError('l2-invalid-exec-exit')
                    self.launcher = 'exited-zero' if value['exitcode'] == 0 else 'exited-error'
            raw_status = self._read('status')
            status = _json(raw_status)
            self.job = status.get('state', 'unknown')
            if (self.job != 'finished' or status.get('run_id') != self.identity['guest_run_id'] or
                    status.get('boot_id') != self._boot):
                raise JobError('l2-not-finished-or-foreign-status')
            raw_report = self._read('report')
            if self._read('status-after') != raw_status:
                raise JobError('l2-results-changed')
            if self.profile.name in SERVICE_PROFILES:
                self._journal()
            self._fresh_boot()
            report = _json(raw_report)
            self._same_chain(report)
            result = assess(report, status, self.plan)
            self._save('assessment.json', json.dumps(result, sort_keys=True).encode())
            self.assessment = result
            self.verification = result['validation']['status']
        except (OSError, ValueError, UnicodeError, RecursionError):
            self._evidence('l2-collect-unverified')
            raise JobError('l2-result-UNVERIFIED') from None
        finally:
            if self.submission != 'not-submitted':
                self._remember()
        self._evidence('l2-collected')
        return self.snapshot()

    def _same_chain(self, report):
        """The guest's list of boots must be the one the controller saw, element by element."""
        guest = report.get('guest') if isinstance(report, dict) else None
        boots = guest.get('boot_ids') if isinstance(guest, dict) else None
        chain = list(self.vm.boot_chain)
        if (boots is not None or self.plan['planned_reboots']) and boots != chain:
            shown = boots if (isinstance(boots, list) and len(boots) <= 8 and
                              all(isinstance(b, str) and len(b) <= 64 for b in boots)) else None
            self._evidence('l2-boot-chain-mismatch', controller=chain, guest=shown)
            raise JobError('l2-boot-chain-mismatch')

    @_guest_serialized
    def full_journal(self):
        """Keep the whole journal of the service for this boot (a diagnostic run, after `collect`).

        The one command of `JOURNAL_FULL_COMMAND`, run once through the guest agent with its output captured.
        Nothing of the guest's answer is used but that output, and nothing of the assessment depends on it: a
        failure raises a `JobError` for the controller to note and changes no result already collected.
        """
        self.grace = JOURNAL_FULL_GRACE
        try:
            self._fresh_boot()
            path, arguments = JOURNAL_FULL_COMMAND
            started = self._rpc('guest-exec', dict(path=path, arg=list(arguments), **{'capture-output': True}))
            if (type(started) is not dict or set(started) != {'pid'} or type(started['pid']) is not int
                    or not 0 < started['pid'] < 2**31):
                self.vm.qga.invalidate()
                raise JobError('l2-invalid-journal-pid')
            for _ in range(JOURNAL_FULL_POLLS):
                status = self._rpc('guest-exec-status', dict(pid=started['pid']), JOURNAL_FULL_REPLY_SECONDS)
                if type(status) is not dict or type(status.get('exited')) is not bool:
                    raise JobError('l2-invalid-exec-status')
                if status['exited']:
                    break
                time.sleep(.5)
            else:
                raise JobError('l2-journal-timeout')
            if status.get('exitcode') != 0:
                self._evidence('l2-file', file='journal-full', complete=False, exitcode=status.get('exitcode'))
                raise JobError('l2-journal-command-failed')
            encoded = status.get('out-data', '')
            if type(encoded) is not str or len(encoded) > 4 * JOURNAL_FULL_OUTPUT // 3 + 4:
                raise JobError('l2-journal-output-invalid')
            try:
                raw = base64.b64decode(encoded, validate=True)
            except ValueError:
                raise JobError('l2-journal-output-invalid') from None
            data = bound_journal(clean_journal(raw))
            self._save(JOURNAL_FULL, data)
            cut = len(data) != len(raw) or status.get('out-truncated') is True
            self._evidence('l2-file', file='journal-full', complete=not cut, size=len(data), source_size=len(raw),
                           sha256=hashlib.sha256(data).hexdigest())
            return dict(size=len(data), source_size=len(raw), complete=not cut)
        finally:
            self.grace = 0

    def snapshot(self):
        result = dict(identity=self.identity, submission=self.submission, launcher=self.launcher,
                      job=self.job, verification=self.verification, assessment=self.assessment,
                      accepted=bool(self.assessment and self.verification == 'PASS' and
                                    self.launcher != 'exited-error' and
                                    self.assessment['acceptance']['accepted']),
                      security_invariants='UNVERIFIED', release_gate=False)
        if self.plan['planned_reboots']:
            result['boot_chain'] = list(self.vm.boot_chain)
        return result
