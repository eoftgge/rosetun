class Profile(NamedTuple):
    """What one stage delivers: the single place that names its files and job.env."""
    name: str
    stage: str        # provenance.stage the build recorded
    sources: tuple    # scripts and catalog, byte-compared with the checkout; the catalog is last
    binaries: tuple   # ELF x86-64 files under artifacts/
    attested: tuple   # binaries whose SHA-256 provenance.json records
    packaged: tuple   # (artifact, path in the checkout): text compared with the checkout
    requests: tuple   # generated by l3_requests and compared with its output
    env: tuple        # job.env fields in file order
    packages: tuple = ()  # Debian packages under artifacts/, after the binaries; never opened beyond their magic

    @property
    def artifacts(self):
        return tuple('artifacts/' + n for n in self.binaries + self.packages + tuple(a for a, _ in self.packaged) +
                     self.requests) + ('artifacts/provenance.json',)

    @property
    def payload(self):
        return self.sources + ('job.env',) + self.artifacts

    @property
    def files(self):
        return self.payload + ('manifest.sha256',)

    @property
    def elf(self):
        return tuple('artifacts/' + n for n in self.binaries)

    @property
    def debs(self):
        return tuple('artifacts/' + n for n in self.packages)

    def limit(self, name):
        """The size bound of one file of the package."""
        return ELF_LIMIT if name in self.elf else PACKAGE_LIMIT if name in self.debs else 256 * 1024


